param([switch]$Flash, [string]$Port, [string]$BuildDir = 'build', [string]$LanIp = '', [string]$IdfProfile = 'C:\Espressif\tools\Microsoft.v6.1.PowerShell_profile.ps1')
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$firmwareDir = Join-Path $projectRoot 'firmware'
foreach ($key in @('MSYSTEM','MSYS','MSYS2_PATH_TYPE','MINGW_PREFIX','MINGW_CHOST','MINGW_PACKAGE_PREFIX','MSYSTEM_PREFIX','CHERE_INVOKING','OSTYPE','MACHTYPE')) {
    Remove-Item "Env:$key" -ErrorAction SilentlyContinue
}
$env:PATH = (($env:PATH -split ';' | Where-Object { $_ -and $_ -notmatch 'msys|mingw|Git\\bin|Git\\usr' }) -join ';')
if (Test-Path -LiteralPath $IdfProfile) { . $IdfProfile *> $null }
if (-not $env:IDF_PATH) { throw 'Open an ESP-IDF PowerShell terminal first, or pass -IdfProfile.' }
$env:IDF_CCACHE_ENABLE = '0'
$env:PYTHONUTF8 = '1'
# Minimal provisioning defaults: bridge URL/token are generated from
# voice-bridge/.env + the active LAN IPv4. The token only lands in the
# generated header; it is never printed or hand-written into source.
$envFile = Join-Path $projectRoot 'voice-bridge\.env'
if (-not (Test-Path -LiteralPath $envFile)) { throw "Missing $envFile (DEVICE_TOKEN/PORT required)." }
$envMap = @{}
foreach ($line in Get-Content -LiteralPath $envFile) {
    if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$') { $envMap[$Matches[1]] = $Matches[2].Trim() }
}
if (-not $envMap['DEVICE_TOKEN']) { throw 'DEVICE_TOKEN missing from voice-bridge/.env.' }
$bridgePort = if ($envMap['PORT']) { $envMap['PORT'] } else { '8780' }
$candidates = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object { $_.IPAddress -notmatch '^(127\.|169\.254\.|172\.(1[6-9]|2[0-9]|3[01])\.|198\.18\.)' -and $_.InterfaceAlias -notmatch 'vEthernet|Hyper-V|WSL|Loopback' }
$preferred = $candidates | Where-Object { $_.InterfaceAlias -match 'WLAN|Wi-?Fi|Wireless|以太网|Ethernet' } | Select-Object -First 1
if (-not $preferred) { $preferred = $candidates | Select-Object -First 1 }
$lanIp = if ($LanIp) { $LanIp } elseif ($preferred) { $preferred.IPAddress } else { '10.1.41.11' }
# PUBLIC_BRIDGE_URL (e.g. a wss tunnel) overrides LAN detection when present.
# The bridge WebSocket endpoint is /voice, so the URL must carry that path.
$bridgeUrl = if ($envMap['PUBLIC_BRIDGE_URL']) { $envMap['PUBLIC_BRIDGE_URL'] } else { "ws://${lanIp}:${bridgePort}/voice" }
$platformUrl = "http://${lanIp}:5173"
$header = "// Generated by tools/build.ps1 from voice-bridge/.env + active LAN IPv4. Do not edit.`n#pragma once`n#define DEFAULT_BRIDGE_URL `"$bridgeUrl`"`n#define DEFAULT_PLATFORM_URL `"$platformUrl`"`n#define DEFAULT_DEVICE_TOKEN `"$($envMap['DEVICE_TOKEN'])`"`n"
Set-Content -LiteralPath (Join-Path $firmwareDir 'main\voice_defaults.h') -Value $header -Encoding ascii -NoNewline
Write-Host "Voice defaults: bridge=$bridgeUrl platform=$platformUrl token=<from .env>"
Push-Location $firmwareDir
try {
    idf.py -B $BuildDir build
    if ($LASTEXITCODE -ne 0) { throw 'ESP-IDF build failed.' }
    if ($Flash) {
        if (-not $Port) { throw 'For flashing, pass -Port COMx.' }
        idf.py -B $BuildDir -p $Port flash
        if ($LASTEXITCODE -ne 0) { throw 'Flash failed.' }
    }
} finally { Pop-Location }
